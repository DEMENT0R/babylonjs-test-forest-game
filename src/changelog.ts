const SEEN_KEY = 'tihaya-polyana-changelog-seen';

/** Есть записи новее тех, что игрок уже открывал. */
export function hasUnseenChanges(): boolean {
  try {
    return localStorage.getItem(SEEN_KEY) !== CHANGELOG[0].date;
  } catch {
    return false;
  }
}

export function markChangesSeen(): void {
  try {
    localStorage.setItem(SEEN_KEY, CHANGELOG[0].date);
  } catch {
    // Без хранилища отметка просто не запомнится
  }
}
